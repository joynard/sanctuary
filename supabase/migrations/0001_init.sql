-- Sanctuary cloud foundation.
-- Offline writes remain authoritative on-device. These tables are the push sync
-- target, keyed per authenticated anonymous user and per client-generated id.
--
-- Setup:
--   1. Enable anonymous sign-ins in Supabase Auth.
--   2. Apply this migration with `supabase db push` or the SQL editor.
--   3. Never ship a service_role key in the Android app. The app uses an
--      authenticated user's access token with the anon/publishable key.
--   RLS uses auth.uid(); anonymous users use the authenticated role, not anon.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    display_name text not null check (char_length(display_name) between 1 and 40),
    daily_goal integer not null default 100 check (daily_goal between 20 and 500),
    intention text check (intention is null or char_length(intention) <= 120),
    timezone_id text not null,
    onboarding_complete boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.scroll_sessions (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users (id) on delete cascade,
    -- UUID generated by the Android client; unique per user for idempotent upserts.
    client_id text not null check (char_length(client_id) between 1 and 64),
    platform text not null check (platform in ('tiktok', 'instagram', 'youtube')),
    local_day date not null,
    started_at timestamptz not null,
    ended_at timestamptz not null,
    scroll_count integer not null check (scroll_count >= 0),
    source text not null default 'accessibility'
        check (source in ('accessibility', 'manual', 'import')),
    device_id text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint scroll_sessions_time_order check (ended_at >= started_at),
    constraint scroll_sessions_user_client_unique unique (user_id, client_id)
);

create index if not exists scroll_sessions_user_day_idx
    on public.scroll_sessions (user_id, local_day desc);

create index if not exists scroll_sessions_user_updated_idx
    on public.scroll_sessions (user_id, updated_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
before update on public.profiles
for each row execute function public.touch_updated_at();

drop trigger if exists scroll_sessions_touch_updated_at on public.scroll_sessions;
create trigger scroll_sessions_touch_updated_at
before update on public.scroll_sessions
for each row execute function public.touch_updated_at();

alter table public.profiles enable row level security;
alter table public.scroll_sessions enable row level security;

revoke all on table public.profiles from anon;
revoke all on table public.scroll_sessions from anon;
grant select, insert, update, delete on table public.profiles to authenticated;
grant select, insert, update, delete on table public.scroll_sessions to authenticated;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own"
    on public.profiles for select
    to authenticated
    using (auth.uid() = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own"
    on public.profiles for insert
    to authenticated
    with check (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
    on public.profiles for update
    to authenticated
    using (auth.uid() = id)
    with check (auth.uid() = id);

drop policy if exists "profiles_delete_own" on public.profiles;
create policy "profiles_delete_own"
    on public.profiles for delete
    to authenticated
    using (auth.uid() = id);

drop policy if exists "scroll_sessions_select_own" on public.scroll_sessions;
create policy "scroll_sessions_select_own"
    on public.scroll_sessions for select
    to authenticated
    using (auth.uid() = user_id);

drop policy if exists "scroll_sessions_insert_own" on public.scroll_sessions;
create policy "scroll_sessions_insert_own"
    on public.scroll_sessions for insert
    to authenticated
    with check (auth.uid() = user_id);

drop policy if exists "scroll_sessions_update_own" on public.scroll_sessions;
create policy "scroll_sessions_update_own"
    on public.scroll_sessions for update
    to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

drop policy if exists "scroll_sessions_delete_own" on public.scroll_sessions;
create policy "scroll_sessions_delete_own"
    on public.scroll_sessions for delete
    to authenticated
    using (auth.uid() = user_id);
