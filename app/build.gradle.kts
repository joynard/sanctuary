val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.isFile) {
        file.inputStream().use { load(it) }
    }
}

fun buildConfigString(key: String): String {
    val value = localProperties.getProperty(key).orEmpty().trim()
        .replace("\\", "\\\\")
        .replace("\"", "\\\"")
    return "\"$value\""
}

